import type { Metadata } from "next";
import Link from "next/link";
import { PIPELINES } from "@/lib/pipelines";
import { PROFILE } from "@/lib/profile";
import { SITE_URL } from "@/lib/site";

const DESCRIPTION =
  "Automation that runs without me: a security blog that writes and publishes itself, an agent-driven trading-card art pipeline, a multi-account posting engine, and the dashboard that watches all of it.";

export const metadata: Metadata = {
  title: `Lab / ${PROFILE.name}`,
  description: DESCRIPTION,
  alternates: { canonical: `${SITE_URL}/lab` },
  openGraph: {
    title: `Lab / ${PROFILE.name}`,
    description: DESCRIPTION,
    type: "website",
    url: `${SITE_URL}/lab`,
    images: [{ url: `${SITE_URL}/lab/covers/bonkdao.webp`, alt: "A cover image generated by one of the pipelines" }],
  },
  twitter: {
    card: "summary_large_image",
    title: `Lab / ${PROFILE.name}`,
    description: DESCRIPTION,
    images: [`${SITE_URL}/lab/covers/bonkdao.webp`],
  },
};

export default function Lab() {
  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "CollectionPage",
    name: `${PROFILE.displayName} — lab`,
    description: DESCRIPTION,
    url: `${SITE_URL}/lab`,
    author: { "@type": "Person", name: PROFILE.displayName, alternateName: PROFILE.name, url: SITE_URL },
    mainEntity: {
      "@type": "ItemList",
      itemListElement: PIPELINES.map((pipeline, index) => ({
        "@type": "ListItem",
        position: index + 1,
        item: {
          "@type": "SoftwareApplication",
          name: pipeline.title,
          description: pipeline.tagline,
          applicationCategory: "DeveloperApplication",
          operatingSystem: "Linux",
        },
      })),
    },
  };

  return (
    <main className="labmain">
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }} />
      <h1>Lab</h1>
      <p className="labintro">
        Four systems that keep running when I am asleep or on a plane.
        Explore what they produce, then open the details to see how they work.
      </p>
      <nav className="labjump" aria-label="Jump to a system">
        {PIPELINES.map((pipeline, index) => (
          <a key={pipeline.id} href={`#${pipeline.id}`}>
            <span>{String(index + 1).padStart(2, "0")}</span>{pipeline.shortTitle}
          </a>
        ))}
      </nav>

      <ol className="pipelist">
        {PIPELINES.map((pipeline, index) => (
          <li key={pipeline.id} className="pipe" id={pipeline.id}>
            <header className="pipehead">
              <span className="pipeindex" aria-hidden="true">
                {String(index + 1).padStart(2, "0")}
              </span>
              <h2>{pipeline.title}</h2>
              <span className="pipecadence">{pipeline.cadence}</span>
            </header>

            <p className="pipetag">{pipeline.tagline}</p>

            {pipeline.artifacts && (
              <figure className={`pipeart ${pipeline.artifactShape ?? "wide"}`}>
                <div className="pipestrip">
                  {pipeline.artifacts.map((artifact) => (
                    // eslint-disable-next-line @next/next/no-img-element
                    <img key={artifact.src} src={artifact.src} alt={artifact.alt} loading="lazy" />
                  ))}
                </div>
                <figcaption>Output of the pipeline itself, unretouched.</figcaption>
              </figure>
            )}

            <dl className="pipefacts">
              <dt>Shipped</dt>
              <dd>
                <ul>
                  {pipeline.shipped.map((line) => (
                    <li key={line}>{line}</li>
                  ))}
                </ul>
              </dd>
            </dl>

            {(pipeline.evidence || pipeline.post) && (
              <p className="pipelinks">
                {pipeline.post && <Link href={`/blog/${pipeline.post}`}>read the build log →</Link>}
                {pipeline.evidence?.map((link) => (
                  <a key={link.href} href={link.href} rel="noopener noreferrer" target="_blank">
                    {link.label} →
                  </a>
                ))}
              </p>
            )}
            <details className="pipedetails">
              <summary>How it works <span aria-hidden="true">+</span></summary>
              <ol className="stages" aria-label={`${pipeline.title} stages`}>
                {pipeline.stages.map((stage) => (
                  <li key={stage.name}>
                    <b>{stage.name}</b>
                    <span>{stage.detail}</span>
                  </li>
                ))}
              </ol>

              <div className="pipebody">
                <p>{pipeline.why}</p>
                <p>{pipeline.mechanic}</p>
              </div>

              {pipeline.note && <p className="pipenote">{pipeline.note}</p>}

              <dl className="pipefacts">
                <dt>Built on</dt>
                <dd className="piperuntime">
                  {pipeline.runtime.map((tool) => (
                    <span key={tool}>{tool}</span>
                  ))}
                </dd>
              </dl>
            </details>
          </li>
        ))}
      </ol>

      <p className="labfootnote">
        Everything here runs on one Linux box under my desk, on systemd timers and cron, with Claude Code as the
        model in the loop rather than a hosted API. The full schedule lives in the last one on this list.
      </p>
    </main>
  );
}
